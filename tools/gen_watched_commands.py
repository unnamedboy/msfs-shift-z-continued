"""Generate src/wasm/watched_commands.h: the SimConnect names of the commands that conflict detection watches.

The names come from the key event tables of the MSFS 2024 SDK documentation (first column, "Key Name").
SimConnect_MapClientEventToSimEvent takes these names, and they differ from the KEY_ macros of
MSFS_EventsEnum.h in places: the command a keyboard binding runs as KEY_AUTOCOORD_TOGGLE is "AUTORUDDER_TOGGLE",
while the SimConnect event "AUTOCOORD_TOGGLE" is another command.

Usage: python tools/gen_watched_commands.py [folder with the saved <page>.md files]
Without a folder the pages are downloaded from docs.flightsimulator.com. Names listed in
tools/unknown_commands.txt (rejected by the sim in a test) are left out.
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src' / 'wasm' / 'watched_commands.h'
UNKNOWN = Path(__file__).resolve().parent / 'unknown_commands.txt'
URL = 'https://docs.flightsimulator.com/msfs2024/flighting/programming-apis/key-events/{}/index.md'
PAGES = [
    'aircraft-autopilot-and-flight-assistance-events',
    'aircraft-electrical-events',
    'aircraft-engine-events',
    'aircraft-flight-control-events',
    'aircraft-fuel-system-events',
    'aircraft-general-systems-events',
    'aircraft-instrumentation-events',
    'aircraft-miscellaneous-events',
    'aircraft-radio-navigation-events',
    'helicopter-specific-events',
    'balloon-and-airship-specific-events',
    'miscellaneous-events',
    'view-and-camera-events',
]
NAME = re.compile(r'`([A-Z0-9_]+)`')
# Not watched: axes and value setters (controllers and gauges send them continuously, key bindings do not
# run them) and the debug commands.
EXCLUDED = re.compile(r'^(AXIS_|DEBUG_)|_SET$|_SET_')


def parse_names(markdown):
    """Names in the first column of the key event tables; one row can list several (ENGINE1..4)."""
    names = []
    for line in markdown.splitlines():
        if line.startswith('|') and '{{< anchor' in line:
            names += NAME.findall(line.strip().strip('|').split('|')[0])
    return names


def read_unknown(text):
    """Names from unknown_commands.txt: one per line, # starts a comment."""
    return {line.strip() for line in text.splitlines() if line.strip() and not line.startswith('#')}


def watched(names, unknown=frozenset()):
    """Documented names minus the excluded kinds and the names the sim rejected."""
    return sorted({name for name in names if not EXCLUDED.search(name) and name not in unknown})


def render(names):
    lines = ['// Generated by tools/gen_watched_commands.py from the MSFS 2024 SDK documentation. Do not edit.',
             '#pragma once',
             '',
             '#include <cstddef>',
             '',
             'namespace shiftz {',
             '',
             'constexpr const char* kWatchedCommands[] = {']
    lines += [f'    "{name}",' for name in names]
    lines += ['};',
              'constexpr size_t kWatchedCommandCount = sizeof(kWatchedCommands) / sizeof(kWatchedCommands[0]);',
              '',
              '}  // namespace shiftz']
    return '\n'.join(lines) + '\n'


def read_page(folder, page):
    if folder:
        return (folder / f'{page}.md').read_text(encoding='utf-8')
    request = urllib.request.Request(URL.format(page), headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode('utf-8')


def main():
    folder = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    names = []
    for page in PAGES:
        found = parse_names(read_page(folder, page))
        if not found:
            raise SystemExit(f'No key events found on {page}')
        names += found
    result = watched(names, read_unknown(UNKNOWN.read_text(encoding='utf-8')))
    OUTPUT.write_text(render(result), encoding='utf-8')
    print(f'{len(result)} of {len(set(names))} commands written to {OUTPUT}')


if __name__ == '__main__':
    main()
